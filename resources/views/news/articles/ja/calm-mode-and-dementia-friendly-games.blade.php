<h2>やさしいモード</h2>
<p>やさしいモードは、ポータル全体でアニメーションを減らし、明るい色をおさえます。ヘッダー（スマートフォンではメニュー）の、ライト／ダークモード切り替えのとなりでオンにできます。選んだ設定は、その端末に保存されます。</p>

<h2>殿堂入り</h2>
