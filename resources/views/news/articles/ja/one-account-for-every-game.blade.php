<p>nikniq.com のゲームに新しいおうちができました。このポータルでは、Space Invaders、Packman、Missile Command などのアーケードの名作から、パズル、神経衰弱、サンドボックスの Blockworld まで、すべての NikniQ ゲームを一か所にまとめています。どれもワンクリックで遊べます。</p>

<h2>一度サインインすれば、どこでも遊べる</h2>
<p>ゲームはそれぞれ別のサブドメインにありますが、ゲームごとにアカウントを作る必要はもうありません。メールアドレスか Google で作ったひとつの NikniQ アカウントで、対応しているすべてのゲームにサインインできます。新規登録で入力するのはメールアドレスだけです。アドレスを確認したあとで、パスワードを設定します。</p>

<h2>スコアを一か所に</h2>
<p>サインインして遊ぶと、ゲームがスコアや進み具合をポータルに送ります。<a href="{{ route('dashboard') }}">マイページ</a>には、すべてのゲームでのベストスコア、プレイ回数、順位がまとまり、ゲームごとにランキングもあります。</p>

<h2>お気に入り</h2>
<p>ゲームの星をタップすると、お気に入りに保存できます。<strong>お気に入り</strong>の絞り込みを使えば、サインインしたどの端末からでも、好きなゲームだけを表示できます。</p>

