<p>ポータルが新しいデザインになりました。ゲームをもっと早く見つけて、もっと気軽に遊べるようにしています。</p>

<h2>ゲームが見つけやすく</h2>
<ul>
    <li>ゲーム一覧の一番上で、注目のゲームがお出迎えします。</li>
    <li>検索、ジャンル、絞り込み、並べ替えをひとつのパネルにまとめました。入力するにつれて結果が絞り込まれます。</li>
    <li>何で遊ぶか迷ったら、<a href="{{ route('games.random') }}">🎲 おまかせ</a>がゲームを選びます。</li>
    <li>カードは絵の下にタイトルを表示し、わかりやすい「遊ぶ」ボタンをひとつだけ置きました。スマートフォンでは見やすい2列表示になります。</li>
</ul>

<h2>ゲーム制作者向けツールキット</h2>
<p>小さな JavaScript ファイルひとつで、どのゲームも NikniQ アカウントにつながるようになりました。プレイヤーはワンタップでサインインでき、ゲームが送ったスコアはプレイヤーのマイページとゲームのランキングに表示されます。手順は<a href="{{ route('developers') }}">開発者向けページ</a>をご覧ください。</p>

<h2>あなたのデータは、あなたが決める</h2>
<p>プロフィールから、当サイトが保有するあなたのデータをすべてダウンロードしたり、アカウントとすべてのデータを削除したりできます。何を集めているのか、なぜなのかは<a href="{{ route('privacy') }}">プライバシーポリシー</a>で説明しています。</p>
