<p>Games are for everyone. This update makes it easier to find games that are relaxing to play, and to make the whole site gentler on the eyes.</p>

<h2>Dementia-friendly games</h2>
<p>A new <strong>Dementia-friendly</strong> filter in the catalogue shows games with a calm pace, simple rules and no time pressure. These games carry a <em>Calm</em> label on their cards. They suit players living with dementia, and anyone who wants a quieter game.</p>
<p><a href="{{ route('games.index', ['dementia' => 1]) }}">See the dementia-friendly games</a></p>

<h2>Calm mode</h2>
<p>Calm mode reduces animation and softens bright colours across the portal. Switch it on from the header (or the menu on phones), next to the light and dark theme toggle. Your choice is remembered on that device.</p>

<h2>Hall of fame</h2>
<p>For players who enjoy a challenge, the new <a href="{{ route('hall') }}">Hall of fame</a> ranks players by their top-three finishes across every game. You can make your profile public, or keep it private, from your profile page.</p>
