<p>Les jeux de nikniq.com ont une nouvelle maison. Le portail réunit tous les jeux NikniQ au même endroit, des classiques d’arcade comme Space Invaders, Packman et Missile Command aux casse-têtes, jeux de mémoire et au bac à sable Blockworld, chacun à portée de clic.</p>

<h2>Connectez-vous une fois, jouez partout</h2>
<p>Chaque jeu a son propre sous-domaine, mais vous n’avez plus besoin d’un compte pour chacun. Un seul compte NikniQ, créé avec votre adresse e-mail ou Google, vous connecte à tous les jeux compatibles. L’inscription ne demande que votre adresse e-mail ; vous choisissez un mot de passe après avoir confirmé l’adresse.</p>

<h2>Vos scores, au même endroit</h2>
<p>Quand vous jouez connecté, les jeux envoient vos scores et votre progression au portail. Votre <a href="{{ route('dashboard') }}">tableau de bord</a> rassemble vos meilleurs scores, votre nombre de parties et votre rang dans chaque jeu, et chaque jeu a son propre classement.</p>

<h2>Favoris</h2>
<p>Touchez l’étoile d’un jeu pour l’ajouter à vos favoris. Utilisez le filtre <strong>Mes favoris</strong> pour n’afficher que les jeux que vous aimez, sur tous les appareils où vous vous connectez.</p>

