<p>nikniq.com tiene un nuevo hogar para sus juegos. El portal reúne todos los juegos de NikniQ en un solo lugar, desde clásicos arcade como Space Invaders, Packman y Missile Command hasta puzles, juegos de memoria y el mundo abierto de Blockworld, cada uno a un clic.</p>

<h2>Inicia sesión una vez y juega en todas partes</h2>
<p>Cada juego vive en su propio subdominio, pero ya no necesitas una cuenta distinta para cada uno. Una sola cuenta de NikniQ, creada con tu correo electrónico o con Google, te permite entrar en todos los juegos compatibles. Para registrarte solo te pedimos tu correo; eliges una contraseña después de confirmar la dirección.</p>

<h2>Tus puntuaciones, en un solo lugar</h2>
<p>Cuando juegas con la sesión iniciada, los juegos envían tus puntuaciones y tu progreso al portal. Tu <a href="{{ route('dashboard') }}">panel</a> reúne tus mejores puntuaciones, cuántas partidas has jugado y tu puesto en cada juego, y cada juego tiene su propia clasificación.</p>

<h2>Favoritos</h2>
<p>Toca la estrella de cualquier juego para guardarlo en tus favoritos. Usa el filtro <strong>Mis favoritos</strong> para ver solo los juegos que te encantan, en cualquier dispositivo donde inicies sesión.</p>

