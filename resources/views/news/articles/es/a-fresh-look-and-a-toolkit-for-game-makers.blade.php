<h2>Herramientas para creadores de juegos</h2>
<p>Ahora cualquier juego puede conectarse a las cuentas de NikniQ con un pequeño archivo JavaScript. Los jugadores inician sesión con un toque y el juego envía las puntuaciones, que aparecen en el panel del jugador y en la clasificación del juego. Consulta la <a href="{{ route('developers') }}">página para desarrolladores</a> para ver una guía paso a paso.</p>

