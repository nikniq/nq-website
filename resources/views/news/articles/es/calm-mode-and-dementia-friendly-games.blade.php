<h2>Juegos aptos para personas con demencia</h2>
<p>Un nuevo filtro <strong>Aptos para demencia</strong> en el catálogo muestra juegos de ritmo tranquilo, reglas sencillas y sin prisas. Estos juegos llevan la etiqueta <em>Tranquilo</em> en su tarjeta. Son adecuados para personas que viven con demencia y para cualquiera que quiera un juego más sosegado.</p>
<p><a href="{{ route('games.index', ['dementia' => 1]) }}">Ver los juegos aptos para personas con demencia</a></p>

<h2>Modo tranquilo</h2>
<p>El modo tranquilo reduce las animaciones y suaviza los colores intensos en todo el portal. Actívalo desde la cabecera (o desde el menú en el móvil), junto al botón de tema claro y oscuro. Tu elección se recuerda en ese dispositivo.</p>

<h2>Salón de la fama</h2>
<p>Para quienes disfrutan de un reto, el nuevo <a href="{{ route('hall') }}">Salón de la fama</a> ordena a los jugadores según sus puestos entre los tres primeros en todos los juegos. Desde tu página de perfil puedes hacer público tu perfil o mantenerlo privado.</p>
